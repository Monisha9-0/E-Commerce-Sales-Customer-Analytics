--->16.WRITE A QUERY TO FIND CUSTOMERS WHOSE LATEST ORDER AMOUNT IS GREATER THAN THEIR PREVIOUS ORDER AMOUNT.
WITH ORDERCOMPARISION AS
(
SELECT
C.[CustomerID],
CONCAT(C.[FirstName],'',C.[LastName]) AS CUSTOMER_NAME,
O.[OrderDate],
O.[TotalAmount] AS ORDERAMOUNT,
LAG(O.TOTALAMOUNT) OVER(PARTITION BY O.CUSTOMERID ORDER BY O.ORDERDATE) AS PREVIOUS_ORDERAMOUNT,
ROW_NUMBER() OVER (PARTITION BY O.CUSTOMERID ORDER BY O.ORDERDATE DESC) AS RN
FROM CUSTOMERS AS  C
JOIN
[dbo].[orders EC]AS O
ON C.[CustomerID]=O.[CustomerID]
)
SELECT
CUSTOMERID,
CUSTOMER_NAME,
ORDERDATE AS LATEST_ORDERDATE,
ORDERAMOUNT AS LATEST_ORDERAMOUNT,
PREVIOUS_ORDERAMOUNT,
ROUND((ORDERAMOUNT-PREVIOUS_ORDERAMOUNT)*100.0/NULLIF(PREVIOUS_ORDERAMOUNT,0),2
) AS PERCENTAGEINCREASE
FROM ORDERCOMPARISION WHERE RN=1
AND  PREVIOUS_ORDERAMOUNT IS NOT NULL
AND ORDERAMOUNT> PREVIOUS_ORDERAMOUNT
ORDER BY PERCENTAGEINCREASE DESC

--->17.CREATE A SQL SERVER AFTERUPDATE TRIGGER ON THE ORDERS TATBLE THAT AUTOMATICALLY INSERTS AN AUDIT RECORD WHENEVER TOTALAMOUNT IS CHANGED.

CREATE TABLE ORDERAUDIT
(
AUDITID INT IDENTITY(1,1) PRIMARY KEY,
ORDERID INT,
OLDTOTALAMOUNT DECIMAL(18,2),
NEWTOTALAMOUNT DECIMAL(18,2),
CHANGEDATE DATETIME DEFAULT
GETDATE()
)


CREATE TRIGGER TG_ORDERS
ON [dbo].[orders EC]
AFTER UPDATE
AS
BEGIN
INSERT INTO ORDERAUDIT
(ORDERID,OLDTOTALAMOUNT,NEWTOTALAMOUNT
)
SELECT D.ORDERID,D.TOTALAMOUNT,I.TOTALAMOUNT
FROM DELETED D
INNER JOIN INSERTED I
ON D.ORDERID=I.ORDERID
WHERE D.TOTALAMOUNT<>I.TOTALAMOUNT
END

