--->20.WRITE A QUERY TO ANALYZE EACH CUSTOMER'S MONTHLY SPENDING AND IDENTIFY CUSTOMERS WHOSE SPENDING IN THEIR 
---LATEST ACTIVE MONTH INCREASED BY AT LEAST 20% COMPARED WITH THEIR PREVIOUS ACTIVE MONTH.
WITH MONTHLYSALES AS
(
SELECT
C.[CustomerID],
CONCAT(C.[FirstName],'',C.[LastName]) AS CUSTOMER_NAME,
DATEFROMPARTS(YEAR(O.ORDERDATE),MONTH(O.ORDERDATE),1) AS ORDER_MONTH,
SUM(O.TOTALAMOUNT) AS MONTHLYPURCHASEAMOUNT
FROM [dbo].[CUSTOMERS] AS C
JOIN
[dbo].[orders EC] AS O
ON C.[CustomerID]=O.[CustomerID]
GROUP BY C.CUSTOMERID,
CONCAT(C.[FirstName],'',C.[LastName]),
DATEFROMPARTS(YEAR(O.ORDERDATE),MONTH(O.ORDERDATE),1) 
),MONTHLYCOMPARISION AS
(
SELECT CUSTOMERID,
CUSTOMER_NAME,
ORDER_MONTH,
 MONTHLYPURCHASEAMOUNT,
 LAG(MONTHLYPURCHASEAMOUNT) OVER(PARTITION BY CUSTOMERID ORDER BY ORDER_MONTH) AS PREVIOUSMONTH_PURCHASEAMOUNT,
 ROW_NUMBER()OVER(PARTITION BY CUSTOMERID ORDER BY ORDER_MONTH DESC) AS RNK
 FROM MONTHLYSALES
 )
 SELECT 
 CUSTOMERID,
 CUSTOMER_NAME,
 ORDER_MONTH AS LATESTMONTH,
 MONTHLYPURCHASEAMOUNT AS LATESTMONTH_PURCHASEAMOUNT,
  PREVIOUSMONTH_PURCHASEAMOUNT,
  ROUND(
  (MONTHLYPURCHASEAMOUNT- PREVIOUSMONTH_PURCHASEAMOUNT)*100.0/NULLIF( PREVIOUSMONTH_PURCHASEAMOUNT,0),2
  ) AS PERCENTAGEGROWTH,
  CASE 
  WHEN
  ((MONTHLYPURCHASEAMOUNT- PREVIOUSMONTH_PURCHASEAMOUNT)*100.0/NULLIF( PREVIOUSMONTH_PURCHASEAMOUNT,0)
  )>=20
  THEN 'HIGH GROWTH'
  WHEN(
  (MONTHLYPURCHASEAMOUNT- PREVIOUSMONTH_PURCHASEAMOUNT)*100.0/NULLIF( PREVIOUSMONTH_PURCHASEAMOUNT,0)
  )>=0
  THEN'MODERATE GROWTH'
  ELSE 'DECLINING'
  END AS CUSTOMERCATEGORY
  FROM MONTHLYCOMPARISION
  WHERE RNK=1
  AND  PREVIOUSMONTH_PURCHASEAMOUNT IS NOT NULL
  AND MONTHLYPURCHASEAMOUNT>PREVIOUSMONTH_PURCHASEAMOUNT*1.20
  ORDER BY PERCENTAGEGROWTH DESC














































































 