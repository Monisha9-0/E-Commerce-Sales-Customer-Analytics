FROM
(
SELECT 
C.[CustomerID],
CONCAT(C.[FirstName],'',[LastName]) AS CUSTOMER_NAME,
O.[OrderDate],
O.[TotalAmount],
LAG(O.[TotalAmount]) OVER(PARTITION BY C.[CustomerID] ORDER BY O.[OrderDate]) AS PREVIOUS_ORDERAMOUNT,
