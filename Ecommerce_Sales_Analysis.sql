--->8.CREATE A STORED PROCEDURE THAT ACCEPTS CUSTOMERID AND MINIMUMAMOUNT AS INPUT PARAMETERS.
---CALCULATE THE CUSTOMER'S TOTAL PURCHASE AMOUNT AND STORE IT IN A VARIABLE.
---THEN CLASSIFY THE CUSTOMER BASED ON THEIR TOTAL PURCHASE.

CREATE OR ALTER PROCEDURE
GETCUSTOMERSTATUS
@CustomerID INT,
@MINIMUMAMOUNT DECIMAL(10,2)
AS 
BEGIN
DECLARE @TOTALPURCHASE DECIMAL(10,2);
SELECT @TOTALPURCHASE=COALESCE(SUM(O.TOTALAMOUNT),0)
FROM [dbo].[orders EC] AS O
WHERE O.CustomerID=@CustomerID
SELECT 
C.CUSTOMERID,
CONCAT(C.FIRSTNAME,'',C.LASTNAME) AS CUSTOMERNAME,
@TOTALPURCHASE AS TOTALPURCHASEAMOUNT
FROM [dbo].[CUSTOMERS] AS C
WHERE C.CUSTOMERID=@CUSTOMERID
IF @TOTALPURCHASE>=@MINIMUMAMOUNT
BEGIN 
PRINT 'HIGH VALUE CUSTOMER'
END
ELSE 
BEGIN
PRINT'REGULAR CUSTOMER'
END
END

EXEC GETCUSTOMERSTATUS
@CUSTOMERID=1,
@MINIMUMAMOUNT=50000

--->9.ANALYZE MONTH OVER MONTH ORDER GROWTH FOR EACH CUSTOMER.FOR EVERY CUSTOMER AND MONTH,
---CALCULATE THE TOTAL NUMBER OF ORDERS,THE PREVIOUS MONTH'S ORDER COUNT,AND THE PERCENTAGE CHANGE 
---FROM THE THE PREVIOUS MONTH.ALSO CLASSIFY THE CUSTOMER-MONTH AS GROWTH,DECLINE,OR NO CHANGE BASED ON THE PERCENTAGE CHANGE.
SELECT 
[CustomerID],
 CUSTOMER_NAME,
ORDERYEAR,
ORDERMONTH,
TOTALORDERS,
PREVIOUSMONTHORDERS,
PERCENTAGECHANGE,
CASE
WHEN  PREVIOUSMONTHORDERS IS NULL THEN 'NO PREVIOUS MONTH'
WHEN PERCENTAGECHANGE >0 THEN 'GROWTH'
WHEN PERCENTAGECHANGE <0 THEN 'DECLINE'
ELSE 'NO CHANGE'
END AS GROWTHSTATUS
FROM
(
SELECT
CUSTOMERID,
CUSTOMER_NAME,
ORDERYEAR,
ORDERMONTH,
TOTALORDERS,
LAG(TOTALORDERS) OVER (PARTITION BY CUSTOMERID ORDER BY ORDERYEAR,ORDERMONTH)AS PREVIOUSMONTHORDERS,
(TOTALORDERS-LAG(TOTALORDERS)OVER (PARTITION BY CUSTOMERID ORDER BY ORDERYEAR,ORDERMONTH))*100.0/
NULLIF (LAG(TOTALORDERS) OVER (PARTITION BY CUSTOMERID ORDER BY ORDERYEAR,ORDERMONTH),0) AS PERCENTAGECHANGE
FROM
(
SELECT C.[CustomerID],
CONCAT(C.[FirstName],'',[LastName]) AS CUSTOMER_NAME,
DATEPART (YEAR,O.[OrderDate]) AS ORDERYEAR,
DATEPART (MONTH,O.[OrderDate]) AS ORDERMONTH,
COUNT(*) AS TOTALORDERS
FROM [dbo].[CUSTOMERS] AS C
JOIN
[dbo].[orders EC] AS O
ON C.[CustomerID]=O.[CustomerID]
GROUP BY C.CUSTOMERID,
CONCAT(C.[FirstName],'',[LastName]),
DATEPART (YEAR,O.[OrderDate]),
DATEPART (MONTH,O.[OrderDate]) 
) AS MONTHLYORDERS
)AS FINALDATA
ORDER BY CUSTOMERID,
ORDERYEAR,
ORDERMONTH
